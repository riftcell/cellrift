#!/usr/bin/env bash
# capture-liveness.sh — run ONE liveness-after-abort experiment against a fresh
# real Open5GS HSS, with a root packet capture on the association and the
# peer's own timestamped log, and refuse to hand back artefacts that measured
# the wrong thing.
#
# Usage: bash test/interop/capture-liveness.sh <e0|e1|e2|e3|e4|e5|e6>
# Env:   OUT_ROOT        - where artefacts go (default /tmp/cellrift-liveness)
#        KEEP_UP         - 1 to leave the containers running afterwards (default 0)
#        SCTP_PROC_PATH  - TEST SEAM ONLY. Path the SCTP-availability gate
#                          probes (default /proc/net/sctp). Point it at a
#                          nonexistent path to fire that gate on a machine
#                          where the module cannot be unloaded. Setting it in a
#                          real experiment defeats the check it exists to make.
# Exit:  0  the experiment ran and its artefacts are trustworthy
#        1  the rig refused: the run would have measured the wrong thing
#
# Exit 0 does NOT mean the scenario passed: the baseline scenario fails by
# design (its first step destroys its own association). Exit 1 means the
# artefacts must be discarded, not interpreted; a refusal exits before
# teardown on purpose so they survive inspection, so run down.sh afterwards.
#
# Experiments:
#   e0  baseline: scenarios/diameter/sctp_abort.yaml, unmodified
#   e1  liveness step re-handshakes under a different registered Origin-Host
#   e2  graceful close (abrupt_close) instead of an ABORT
#   e3  no fault at all: two separate processes, same Origin-Host
#   e4  TCP plus reset instead of SCTP plus ABORT
#   e5  e0 with a 35 s settle between the two steps
#   e6  e0 with the Visited-Network-Identifier the HSS requires (valid UARs)
#
# `set -e` is deliberately absent: the baseline scenario exits non-zero and the
# script must carry on to collect the evidence.
set -uo pipefail

cd "$(dirname "$0")/../.."

EXP="${1:-}"
OUT_ROOT="${OUT_ROOT:-/tmp/cellrift-liveness}"
OUT="$OUT_ROOT/$EXP"
SCENARIO=""
FILTER="sctp"
TCPDUMP_PID=""

# refuse is the single exit path for every gate: one loud line on stdout,
# exit 1, no teardown (the artefacts stay on disk for inspection).
refuse() {
  echo "LIVENESS RIG REFUSED: $1"
  exit 1
}

usage_exit() {
  echo "usage: bash test/interop/capture-liveness.sh <e0|e1|e2|e3|e4|e5|e6>"
  exit 1
}

is_tcp_experiment() { [ "$EXP" = "e4" ]; }

# The sctp kernel module does not survive a reboot. Without it Cellrift
# substitutes TCP with a recorded warning, and a run would then produce a
# confident result about the wrong transport. SCTP_PROC_PATH is a test seam
# for proving this gate fires, not a way to skip it.
assert_sctp_available() {
  is_tcp_experiment && return 0
  local probe="${SCTP_PROC_PATH:-/proc/net/sctp}"
  [ -e "$probe" ] && return 0
  refuse "/proc/net/sctp is absent. Run 'sudo modprobe sctp' first - without it Cellrift substitutes TCP with a recorded warning and this run would produce a confident result about the wrong transport."
}

# Common two-step scenario. Parameters are set by the caller through
# S_TRANSPORT, S_IMPAIR, S_ASSERT, S_STEP2_FIELDS and S_MIDDLE so that e0's
# siblings differ from it in exactly the one variable under test.
write_two_step() {
  cat > "$OUT/scenario.yaml" <<EOF
name: liveness experiment $EXP
version: "1.0"
description: generated by capture-liveness.sh, one variable changed from sctp_abort.yaml
protocols:
  diameter:
    transport: $S_TRANSPORT
$S_IDENT_LINES
variables:
  subscriber_msisdn: "447700900001"
  hss_target: "hss.lab.local:3868"
steps:
  - id: uar_fault
    protocol: diameter
    action: send
    target: "{{ hss_target }}"
    message: UAR
    impair:
      $S_IMPAIR
    fields:
      User-Name: "{{ subscriber_msisdn }}"
      Public-Identity: "$S_PUBID"
$S_VNI$S_STEP1_FIELDS    assert:
      - $S_ASSERT
      - response.timed_out == false
$S_MIDDLE  - id: uar_liveness
    protocol: diameter
    action: send
    target: "{{ hss_target }}"
    message: UAR
    fields:
      User-Name: "{{ subscriber_msisdn }}"
      Public-Identity: "$S_PUBID"
$S_VNI$S_STEP2_FIELDS    assert:
      - response.Experimental-Result-Code == 2001
      - response.timed_out == false
EOF
}

reset_scenario_params() {
  S_TRANSPORT="sctp"
  S_IMPAIR="sctp_abort: true"
  S_ASSERT='response.connection_state == "aborted"'
  S_STEP2_FIELDS=""
  S_MIDDLE=""
  S_PUBID="sip:{{ subscriber_msisdn }}@ims.mnc001.mcc001.3gppnetwork.org"
  S_VNI=""
  S_STEP1_FIELDS=""
  S_IDENT_LINES="    origin_host: test.cellrift.local
    origin_realm: cellrift.local"
}

# e1: cx.cellrift.local is chosen because it is ALREADY a registered
# ConnectPeer in hss-freeDiameter.conf, so the control needs no config edit.
# If the peer rejects the CER under it for an unrelated reason, that rejection
# is itself a recorded result, not a reason to silently switch identities.
#
# The protocols block must NOT declare origin_host/origin_realm here: the
# adapter prefers that config over a step's Origin-Host field, so declaring
# them pins both handshakes to one identity and the control would silently
# measure nothing. Each step therefore names its own identity in fields.
write_e1() {
  reset_scenario_params
  S_IDENT_LINES=""
  S_STEP1_FIELDS='      Origin-Host: test.cellrift.local
      Origin-Realm: cellrift.local
'
  S_STEP2_FIELDS='      Origin-Host: cx.cellrift.local
      Origin-Realm: cellrift.local
'
  write_two_step
}

# e6 (added beyond the original six): the committed scenario's UARs omit
# Visited-Network-Identifier, which this HSS's dictionary requires (min 1), so
# every UAR it sends is answered DIAMETER_MISSING_AVP. e6 is e0 with that AVP
# and uar_uaa.yaml's identities, so a valid request crosses the same sequence.
write_e6() {
  reset_scenario_params
  S_PUBID="sip:{{ subscriber_msisdn }}@ims.mnc001.mcc001.3gppnetwork.org"
  S_VNI='      Visited-Network-Identifier: "mnc001.mcc001.3gppnetwork.org"
'
  write_two_step
}

write_e2() {
  reset_scenario_params
  S_IMPAIR="abrupt_close: true"
  S_ASSERT='response.connection_state == "closed"'
  write_two_step
}

# e3: a single un-faulted UAR. The script runs it twice in two processes.
write_e3() {
  cat > "$OUT/scenario.yaml" <<'EOF'
name: liveness experiment e3
version: "1.0"
description: generated by capture-liveness.sh, no fault, second association reuses the identity
protocols:
  diameter:
    transport: sctp
    origin_host: test.cellrift.local
    origin_realm: cellrift.local
variables:
  subscriber_msisdn: "447700900001"
  hss_target: "hss.lab.local:3868"
steps:
  - id: uar_plain
    protocol: diameter
    action: send
    target: "{{ hss_target }}"
    message: UAR
    fields:
      User-Name: "{{ subscriber_msisdn }}"
      Public-Identity: "sip:{{ subscriber_msisdn }}@ims.mnc001.mcc001.3gppnetwork.org"
    assert:
      - response.timed_out == false
EOF
}

write_e4() {
  reset_scenario_params
  S_TRANSPORT="tcp"
  S_IMPAIR="reset: true"
  S_ASSERT='response.connection_state == "reset"'
  write_two_step
}

# e5: 35 s is past the HSS's default 30 s Tc connect-retry timer, so the peer
# may act on its own inside the window.
write_e5() {
  reset_scenario_params
  S_MIDDLE='  - id: settle
    action: wait
    duration_ms: 35000
'
  write_two_step
}

select_scenario() {
  mkdir -p "$OUT"
  if [ "$EXP" = "e0" ]; then
    SCENARIO="scenarios/diameter/sctp_abort.yaml"
    return 0
  fi
  "write_$EXP"
  SCENARIO="$OUT/scenario.yaml"
}

# The peer object in freeDiameter carries state across client processes, so a
# fresh container per experiment is the only way to keep one run from
# measuring another's residue.
boot_fresh_peer() {
  bash test/interop/up.sh || refuse "up.sh failed; there is no peer under test"
  docker inspect -f '{{.State.StartedAt}}' hss > "$OUT/container-start"
}

# Checks the binary the peer ACTUALLY runs, not upstream master. A count of 0
# means the shipped fork does not carry that code path. Never fails the run.
record_fork_check() {
  local f="$OUT/fork-check.txt" lib literal
  docker exec hss sh -c 'find / -name "libfdcore*" 2>/dev/null' | head -40 > "$f"
  lib=$(grep -E 'libfdcore\.so[.0-9]*$' "$f" | head -1)
  for literal in \
    'Unable to forward answer to deleted / closed peer' \
    'Invalid state to receive a new connection attempt' \
    'STATE_OPEN'; do
    echo "count[$literal] in ${lib:-NOT-FOUND}: $(docker exec hss sh -c \
      "grep -ao '$literal' '$lib' | wc -l" 2>&1)" >> "$f"
  done
  { docker exec hss sh -c 'open5gs-hssd -v 2>&1 | head -5'
    docker exec hss sh -c 'head -2 /etc/os-release'; } >> "$f" 2>&1
}

start_capture() {
  is_tcp_experiment && FILTER="tcp port 3868"
  # shellcheck disable=SC2086
  sudo -n tcpdump -i any -s 0 -U -w "$OUT/$EXP.pcap" $FILTER >"$OUT/tcpdump.log" 2>&1 &
  TCPDUMP_PID=$!
  for _ in $(seq 1 50); do
    [ -s "$OUT/$EXP.pcap" ] && return 0
    sleep 0.1
  done
  refuse "tcpdump never started writing to $OUT/$EXP.pcap"
}

stop_capture() {
  sleep 1
  sudo -n kill -INT "$TCPDUMP_PID" 2>/dev/null
  wait "$TCPDUMP_PID" 2>/dev/null
}

# run_cellrift <suffix>: suffix is "" for the first process and "-2" for e3's
# second one.
run_cellrift() {
  local sfx="$1"
  go run ./cmd/cellrift run \
    --target-host 127.0.0.1:3868 \
    --timeout 5000 \
    --format json \
    --output "$OUT/report$sfx.json" \
    "$SCENARIO" > "$OUT/cellrift$sfx.stdout" 2>&1
  echo $? > "$OUT/run$sfx.exit"
}

run_experiment() {
  # e4 is TCP on purpose; the tunable makes that explicit rather than
  # accidental. Every other experiment inherits the caller's environment.
  is_tcp_experiment && export CELLRIFT_TRANSPORT_FALLBACK=tcp
  date +%s.%N > "$OUT/run.start"
  run_cellrift ""
  if [ "$EXP" = "e3" ]; then
    sleep 1
    run_cellrift "-2"
  fi
  date +%s.%N > "$OUT/run.end"
}

gate_report_written() {
  [ -s "$OUT/report.json" ] && return 0
  refuse "cellrift wrote no report - this is a build or startup failure, not a result about the peer"
}

# Loops over EVERY report: e3 writes report.json and report-2.json, and
# checking only the first would let the second association run over TCP while
# the gate reported clean.
gate_no_tcp_substitution() {
  is_tcp_experiment && return 0
  local r
  for r in "$OUT"/report*.json; do
    grep -q "used tcp" "$r" || continue
    refuse "this run asked for SCTP and Cellrift substituted TCP; nothing here says anything about SCTP (seen in $r)"
  done
}

gate_pcap_has_sctp() {
  is_tcp_experiment && return 0
  tshark -r "$OUT/$EXP.pcap" -Y sctp -c 1 2>/dev/null | grep -q . && return 0
  refuse "the capture contains no SCTP packet - a pcap with no SCTP proves nothing about SCTP"
}

gate_peer_was_ready() {
  grep -q "HSS initialize...done" "$OUT/hss.log" && return 0
  refuse "the HSS never logged ready; the peer under test may not have been running"
}

run_gates() {
  gate_report_written
  gate_no_tcp_substitution
  gate_pcap_has_sctp
  gate_peer_was_ready
}

# dissect_fields prints the tshark field list for this experiment's transport.
dissect_fields() {
  if is_tcp_experiment; then
    echo frame.number frame.time_epoch ip.src ip.dst tcp.srcport tcp.dstport tcp.seq tcp.ack
  else
    echo frame.number frame.time_epoch ip.src ip.dst sctp.srcport sctp.dstport \
      sctp.chunk_type sctp.verification_tag sctp.data_tsn sctp.data_sid \
      sctp.data_payload_proto_id sctp.sack_cumulative_tsn_ack
  fi
  echo diameter.cmd.code diameter.flags.request diameter.hopbyhopid diameter.endtoendid
}

run_tshark_fields() {
  local filter='sctp || diameter' decode=(-d sctp.port==3868,diameter) args=() f
  if is_tcp_experiment; then filter='tcp || diameter'; decode=(); fi
  for f in "$@"; do args+=(-e "$f"); done
  tshark -r "$OUT/$EXP.pcap" "${decode[@]}" -Y "$filter" -T fields \
    -E separator=, -E aggregator=';' -E header=y "${args[@]}" > "$OUT/chunks.csv" 2> "$OUT/chunks.stderr"
}

# dissect writes chunks.csv. If this tshark build rejects a field, drop only
# that -e, keep the rejection text in chunks.stderr, and retry.
dissect() {
  local fields bad f kept
  read -r -a fields <<< "$(dissect_fields | tr '\n' ' ')"
  run_tshark_fields "${fields[@]}"
  for _ in 1 2 3; do
    bad=$(grep -E '^\s+[a-z]+\.[a-z_.]+$' "$OUT/chunks.stderr" | tr -d '\t ')
    [ -z "$bad" ] && return 0
    echo "dropped field(s): $bad" >> "$OUT/chunks.dropped"
    kept=()
    for f in "${fields[@]}"; do
      grep -qx "$f" <<< "$bad" || kept+=("$f")
    done
    fields=("${kept[@]}")
    cp "$OUT/chunks.stderr" "$OUT/chunks.stderr.$_"
    run_tshark_fields "${fields[@]}"
  done
}

write_hsslog_grep() {
  grep -nE "Received|SENT|DROPPED|Unable to forward answer|Invalid state|STATE_|CONNECTED TO|Connection reset by peer|error" \
    "$OUT/hss.log" > "$OUT/hsslog-grep.txt"
}

warnings_of() {
  grep -A3 '"warnings"' "$1" 2>/dev/null | head -5
}

# summarise_diameter_rows counts Diameter-bearing rows by src,dst,command,
# request flag, locating columns by header name so a dropped field cannot
# shift them.
summarise_diameter_rows() {
  awk -F, 'NR==1 {for (i=1;i<=NF;i++) c[$i]=i; next}
    $(c["diameter.cmd.code"])!="" {
      print $(c["ip.src"])" > "$(c["ip.dst"])" cmd="$(c["diameter.cmd.code"])" req="$(c["diameter.flags.request"])
    }' "$OUT/chunks.csv" | sort | uniq -c
}

write_summary() {
  {
    echo "experiment: $EXP"
    echo "container-start: $(cat "$OUT/container-start")"
    echo "run.start: $(cat "$OUT/run.start")  run.end: $(cat "$OUT/run.end")"
    echo "run.exit: $(cat "$OUT/run.exit")"
    echo "warnings: $(warnings_of "$OUT/report.json" | grep . || echo none)"
    echo "rows per src,dst,cmd.code,request (from chunks.csv):"
    summarise_diameter_rows
    echo "hsslog-grep lines: $(wc -l < "$OUT/hsslog-grep.txt")"
  } > "$OUT/SUMMARY.txt"
}

main() {
  case "$EXP" in e0|e1|e2|e3|e4|e5|e6) ;; *) usage_exit ;; esac
  assert_sctp_available
  rm -rf "$OUT"
  select_scenario
  boot_fresh_peer
  record_fork_check
  start_capture
  run_experiment
  stop_capture
  docker logs -t hss > "$OUT/hss.log" 2>&1
  run_gates
  dissect
  write_hsslog_grep
  write_summary
  [ "${KEEP_UP:-0}" = "1" ] || bash test/interop/down.sh
  echo "capture-liveness $EXP done; artefacts in $OUT"
}

main
